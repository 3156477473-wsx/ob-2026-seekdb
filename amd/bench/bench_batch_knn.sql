-- seekdb + hipVS 批量检索基准
--
-- 在 AMD Radeon Cloud 的 seekdb-hipvs 模板中执行。
-- 目的是复现「CPU（VSAG）vs GPU（cuVS）」的批量检索耗时对比。
--
-- 用法：
--   1. 启动 seekdb（模板 Notebook 第 3 节）
--   2. 在 seekdb 客户端中逐段执行本文件
--   3. 记录每条 CALL ... batch_knn 的耗时
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 0. 准备：建两张相同的向量表，分别走 CPU 与 GPU 索引
-- ---------------------------------------------------------------------------
DROP TABLE IF EXISTS t_vsag;
DROP TABLE IF EXISTS t_cuvs;

CREATE TABLE t_vsag (
    id INT PRIMARY KEY,
    c2   VECTOR(128)
);

CREATE TABLE t_cuvs LIKE t_vsag;

-- 两侧数据完全一致（模板中用同一份 10000 条向量灌入）
-- 示例：INSERT INTO t_vsag SELECT * FROM source_vectors;
--       INSERT INTO t_cuvs SELECT * FROM source_vectors;

-- ---------------------------------------------------------------------------
-- 1. 建索引：同一份数据，两种 lib
-- ---------------------------------------------------------------------------
CREATE VECTOR INDEX idx_vsag ON t_vsag(c2) WITH (lib=vsag);

CREATE VECTOR INDEX idx_cuvs ON t_cuvs(c2) WITH (lib=cuvs);

-- 记录两条索引的构建耗时，即本题关注的「HNSW 索引构建链路」成本

-- ---------------------------------------------------------------------------
-- 2. 单条查询对比（验证 GPU 在单条场景无收益）
-- ---------------------------------------------------------------------------
-- 单条近似最近邻查询，各自执行多次取最小值
-- SELECT id FROM t_vsag ORDER BY l2_distance(c2, @q) APPROXIMATE LIMIT 10;
-- SELECT id FROM t_cuvs ORDER BY l2_distance(c2, @q) APPROXIMATE LIMIT 10;

-- ---------------------------------------------------------------------------
-- 3. 批量检索对比（核心）
-- ---------------------------------------------------------------------------
-- CPU 路径：嵌套循环，逐条 JOIN，复杂度 O(N × 图遍历)
--   SELECT COUNT(*) FROM (SELECT ... FROM queries JOIN t_vsag ...) ;
--
-- GPU 路径：一次批处理全部 N 条
--   CALL dbms_vector.batch_knn('t_cuvs', probes, k, 'out_table');
--
-- 建议批量：100 / 500 / 1000 / 2000 / 4000
-- 记录每个批量的 CPU 耗时与 GPU 耗时，计算加速比 = cpu_ms / gpu_ms

-- ---------------------------------------------------------------------------
